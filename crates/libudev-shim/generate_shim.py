#!/usr/bin/env python3
"""Regenerates src/shim.c from the extern block of src/lib.rs: one C function per declared libudev function, forwarding to the real
libudev found with dlopen on first use (see build.rs). Run it after changing the declarations: `python3 generate_shim.py`."""
import re
from pathlib import Path

here = Path(__file__).resolve().parent
source = (here / "src/lib.rs").read_text()
block = source[source.index('extern "C" {'):source.index("#[cfg(hwdb)]\nmod hwdb")]
functions = re.findall(r"pub fn (\w+)\((.*?)\)\s*(?:->\s*([^;]+))?;", block)

C_TYPES = {
    "c_int": "int", "c_char": "char", "c_ulonglong": "unsigned long long", "size_t": "size_t", "dev_t": "dev_t",
    "*mut c_void": "void *", "*const c_char": "const char *", "*mut c_char": "char *",
}


def ctype(rust):
    rust = rust.strip()
    if rust in C_TYPES:
        return C_TYPES[rust]
    if rust.startswith("*mut") or rust.startswith("*const"):
        return "void *"  # a pointer to one of the opaque udev structures
    raise SystemExit(f"unmapped type {rust!r}")


PREAMBLE = """/* Generated by generate_shim.py from src/lib.rs; do not edit. libudev functions opened at run time; see build.rs. */
#define _GNU_SOURCE
#include <dlfcn.h>
#include <errno.h>
#include <pthread.h>
#include <stddef.h>
#include <sys/types.h>

static void *sturdy_udev_handle;
static pthread_once_t sturdy_udev_once = PTHREAD_ONCE_INIT;

static void sturdy_udev_open(void) {
    sturdy_udev_handle = dlopen("libudev.so.1", RTLD_NOW | RTLD_LOCAL);
    if (sturdy_udev_handle == NULL) {
        sturdy_udev_handle = dlopen("libudev.so.0", RTLD_NOW | RTLD_LOCAL);
    }
}

/* The function `name` of the real library, or NULL when the library (or the function) is not there. */
static void *sturdy_udev_symbol(const char *name) {
    pthread_once(&sturdy_udev_once, sturdy_udev_open);
    return sturdy_udev_handle != NULL ? dlsym(sturdy_udev_handle, name) : NULL;
}
"""

out = [PREAMBLE]
for name, args, ret in functions:
    params, names, types = [], [], []
    if args.strip():
        for argument in re.split(r",\s*(?=\w+:)", args.strip()):
            arg_name, arg_type = (part.strip() for part in argument.split(":", 1))
            arg_name = {"str": "string"}.get(arg_name, arg_name)
            params.append(f"{ctype(arg_type)} {arg_name}")
            names.append(arg_name)
            types.append(ctype(arg_type))
    return_type = ctype(ret) if ret else "void"
    failure = {"int": "-ENODEV", "unsigned long long": "0ULL", "dev_t": "0"}.get(return_type, "NULL")
    give_up = "return;" if return_type == "void" else f"return {failure};"
    forward = ("" if return_type == "void" else "return ") + f"function({', '.join(names)});"
    out.append(f"""{return_type} {name}({', '.join(params) or 'void'}) {{
    typedef {return_type} (*function_t)({', '.join(types) or 'void'});
    static function_t resolved_function;
    function_t function = __atomic_load_n(&resolved_function, __ATOMIC_ACQUIRE);
    if (function == NULL) {{
        function = (function_t)sturdy_udev_symbol("{name}");
        if (function != NULL) {{
            __atomic_store_n(&resolved_function, function, __ATOMIC_RELEASE);
        }}
    }}
    if (function == NULL) {{
        {give_up}
    }}
    {forward}
}}
""")
(here / "src/shim.c").write_text("\n".join(out))
print(f"{len(functions)} functions")
