use std::{
    env, fs,
    path::{Path, PathBuf},
    process::Command,
};

fn main() {
    emit_version_metadata();
    emit_sturdy_link_directives();
    emit_self_contained_linux();

    if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        println!("cargo:rerun-if-changed=../../Vertex.webp");
        if let Err(error) = compile_windows_resources() {
            println!("cargo:warning=failed to configure Windows resources: {error}");
        }
    }
}

/// On Linux (glibc) the finished executable needs only the C library. The engine's own archives are
/// already static (libstdc++ is linked in by `sturdy-sys`); what is left is:
///   * `libgcc_s.so.1`, which Rust's unwinder pulls in. A directory holding a `libgcc_s.so` linker script that points at the static
///     `libgcc_eh.a` / `libgcc.a` comes first on the search path, so `-lgcc_s` is satisfied from the archives.
///   * glibc symbol versions newer than the floor (a binary built on a current glibc will not start on an older one even though it
///     uses nothing new): the engine's `glibc_compat.c` defines the affected functions in the executable, forwarding to the old
///     versions, and is linked as an object so its definitions win over libc's and libm's.
fn emit_self_contained_linux() {
    let linux_gnu = env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("linux") && env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("gnu");
    if !linux_gnu {
        return;
    }
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));

    // 1. libgcc, statically.
    let compiler = cc::Build::new().get_compiler();
    let print_file = |name: &str| -> Option<PathBuf> {
        let output = Command::new(compiler.path()).arg(format!("-print-file-name={name}")).output().ok()?;
        let path = PathBuf::from(String::from_utf8_lossy(&output.stdout).trim());
        // `-print-file-name` echoes the bare name back when it finds nothing.
        path.is_absolute().then_some(path).filter(|path| path.is_file())
    };
    match (print_file("libgcc_eh.a"), print_file("libgcc.a")) {
        (Some(eh), Some(gcc)) => {
            let directory = out_dir.join("static-libgcc");
            if let Err(error) = fs::create_dir_all(&directory).and_then(|()| {
                fs::write(directory.join("libgcc_s.so"), format!("/* generated by build.rs */\nINPUT({} {})\n", eh.display(), gcc.display()))
            }) {
                println!("cargo:warning=could not write the static libgcc linker script: {error}");
            } else {
                println!("cargo:rustc-link-search=native={}", directory.display());
            }
        }
        _ => println!("cargo:warning=libgcc_eh.a / libgcc.a not found; the binary will need libgcc_s.so.1 at run time"),
    }

    // 2. The glibc floor.
    println!("cargo:rerun-if-env-changed=DEP_STURDY_GLIBC_COMPAT_SOURCE");
    println!("cargo:rerun-if-env-changed=VERTEX_GLIBC_COMPAT_SOURCE");
    // VERTEX_GLIBC_COMPAT_SOURCE points at another copy of the file (an engine checkout being worked on, say).
    let Some(source) = env::var_os("VERTEX_GLIBC_COMPAT_SOURCE")
        .or_else(|| env::var_os("DEP_STURDY_GLIBC_COMPAT_SOURCE"))
        .map(PathBuf::from)
        .filter(|path| path.is_file())
    else {
        println!(
            "cargo:warning=sturdy-sys does not publish glibc_compat.c (an engine older than the self-contained work); \
             the binary will require the glibc of the machine that built it"
        );
        return;
    };
    println!("cargo:rerun-if-changed={}", source.display());
    let objects = cc::Build::new()
        .file(&source)
        .opt_level(2)
        .flag("-fno-builtin")
        .flag("-fno-lto")
        .flag("-fvisibility=hidden")
        .flag("-fno-stack-protector")
        .warnings(false)
        .cargo_metadata(false)
        .compile_intermediates();
    for object in objects {
        println!("cargo:rustc-link-arg={}", object.display());
    }
}

fn emit_sturdy_link_directives() {
    let Ok(path) = env::var("DEP_STURDY_LINK_DIRECTIVES_FILE") else {
        return;
    };
    let path = PathBuf::from(path);
    println!("cargo:rerun-if-changed={}", path.display());
    let contents = match fs::read_to_string(&path) {
        Ok(contents) => contents,
        Err(error) => {
            println!("cargo:warning=failed to read SturdyEngine link directives: {error}");
            return;
        }
    };
    let mut search_dirs = Vec::new();
    for directive in contents.lines() {
        if let Some(search) = directive.strip_prefix("cargo:rustc-link-search=native=") {
            let directory = PathBuf::from(search);
            if !search_dirs.contains(&directory) {
                println!("cargo:rustc-link-search=native={}", directory.display());
                search_dirs.push(directory);
            }
            continue;
        }
        let Some(link) = directive.strip_prefix("cargo:rustc-link-lib=") else {
            continue;
        };
        if let Some(name) = link.strip_prefix("static=") {
            let archive = native_archive_path(name, &search_dirs);
            if let Some(archive) = archive {
                // Put static archives after Rust objects. This preserves the CMake probe's link
                // order and lets one-pass linkers resolve symbols introduced by the Rust rlibs.
                if cfg!(target_os = "windows")
                    && matches!(name, "slang-compiler" | "compiler-core" | "core")
                {
                    // Rust's native libraries are passed to MSVC before Rust rlibs. Slang's
                    // archives satisfy references introduced by those rlibs, so force their
                    // members into the link after the objects have been considered.
                    println!("cargo:rustc-link-arg=/WHOLEARCHIVE:{}", archive.display());
                } else {
                    println!("cargo:rustc-link-arg={}", archive.display());
                }
            }
        } else if let Some(framework) = link.strip_prefix("framework=") {
            println!("cargo:rustc-link-arg=-framework");
            println!("cargo:rustc-link-arg={framework}");
        } else if cfg!(target_os = "windows") {
            println!("cargo:rustc-link-arg={link}.lib");
        } else {
            println!("cargo:rustc-link-arg=-l{link}");
        }
    }
}

fn native_archive_path(name: &str, search_dirs: &[PathBuf]) -> Option<PathBuf> {
    let names = if cfg!(target_os = "windows") {
        vec![format!("{name}.lib")]
    } else {
        vec![format!("lib{name}.a"), format!("lib{name}.so"), format!("lib{name}.dylib")]
    };
    search_dirs
        .iter()
        .flat_map(|directory| names.iter().map(|name| directory.join(name)))
        .find(|path| path.is_file())
}

fn emit_version_metadata() {
    // Cargo always provides the workspace version to build scripts.
    let package_version = env::var("CARGO_PKG_VERSION").expect("cargo sets CARGO_PKG_VERSION");
    let display_version = format_display_version(&package_version);
    println!("cargo:rustc-env=VERTEX_APP_VERSION={display_version}");

    let repo_root = locate_repo_root();
    if let Some(repo_root) = repo_root.as_ref() {
        emit_repo_rerun_rules(&repo_root);
    }

    let revision = repo_root
        .as_deref()
        .and_then(git_revision)
        .unwrap_or_else(|| "unknown".to_owned());
    println!("cargo:rustc-env=VERTEX_GIT_REVISION={revision}");
}

fn format_display_version(package_version: &str) -> String {
    let release = package_version.split('-').next().unwrap_or(package_version);
    let mut release_parts = release.split('.');
    let major = release_parts.next().unwrap_or("0");
    let minor = release_parts.next().unwrap_or("0");
    let patch = release_parts.next().unwrap_or("0");

    let prerelease = package_version
        .split_once('-')
        .map(|(_, suffix)| suffix.split('.').next().unwrap_or(suffix))
        .unwrap_or("");

    let channel = match prerelease.to_ascii_lowercase().as_str() {
        "alpha" => " Alpha",
        "beta" => " Beta",
        "rc" => " RC",
        _ => "",
    };

    format!("{major}.{minor}.{patch}{channel}")
}

fn locate_repo_root() -> Option<PathBuf> {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").ok()?);
    Some(manifest_dir.parent()?.parent()?.to_path_buf())
}

fn locate_git_dir(repo_root: &Path) -> Option<PathBuf> {
    let git_path = repo_root.join(".git");

    if git_path.is_dir() {
        return Some(git_path);
    }

    let git_file = fs::read_to_string(&git_path).ok()?;
    let relative = git_file.trim().strip_prefix("gitdir: ")?.trim();
    Some(repo_root.join(relative))
}

fn emit_repo_rerun_rules(repo_root: &Path) {
    if let Some(git_dir) = locate_git_dir(repo_root) {
        emit_git_rerun_rules(repo_root, &git_dir);
    }

    for path in git_snapshot_paths(repo_root) {
        println!("cargo:rerun-if-changed={}", repo_root.join(path).display());
    }
}

fn emit_git_rerun_rules(repo_root: &Path, git_dir: &Path) {
    println!(
        "cargo:rerun-if-changed={}",
        repo_root.join(".gitignore").display()
    );
    println!("cargo:rerun-if-changed={}", git_dir.join("HEAD").display());
    println!("cargo:rerun-if-changed={}", git_dir.join("index").display());

    if let Ok(head_contents) = fs::read_to_string(git_dir.join("HEAD")) {
        if let Some(reference) = head_contents.trim().strip_prefix("ref: ") {
            println!(
                "cargo:rerun-if-changed={}",
                git_dir.join(reference).display()
            );
        }
    }
}

fn git_revision(repo_root: &Path) -> Option<String> {
    let revision = git_output(repo_root, &["rev-parse", "--short=8", "HEAD"])
        .or_else(|| git_head_revision(repo_root))?;
    let dirty_suffix = matches!(git_worktree_clean(repo_root), Some(false))
        .then_some("-dirty")
        .unwrap_or_default();
    Some(format!("{revision}{dirty_suffix}"))
}

fn git_worktree_clean(repo_root: &Path) -> Option<bool> {
    let output = Command::new("git")
        .args(["status", "--porcelain", "--untracked-files=normal"])
        .current_dir(repo_root)
        .output()
        .ok()?;

    if !output.status.success() {
        return None;
    }

    Some(output.stdout.is_empty())
}

fn git_snapshot_paths(repo_root: &Path) -> Vec<PathBuf> {
    let mut paths = git_path_list(repo_root, &["ls-files", "-z"]).unwrap_or_default();
    for path in git_path_list(
        repo_root,
        &["ls-files", "--others", "--exclude-standard", "-z"],
    )
    .unwrap_or_default()
    {
        if !paths.contains(&path) {
            paths.push(path);
        }
    }

    paths
}

fn git_path_list(repo_root: &Path, args: &[&str]) -> Option<Vec<PathBuf>> {
    let output = Command::new("git")
        .args(args)
        .current_dir(repo_root)
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }

    Some(
        output
            .stdout
            .split(|byte| *byte == 0)
            .filter(|entry| !entry.is_empty())
            .map(|entry| PathBuf::from(String::from_utf8_lossy(entry).into_owned()))
            .collect(),
    )
}

fn git_output(repo_root: &Path, args: &[&str]) -> Option<String> {
    let mut command = Command::new("git");
    command.args(args).current_dir(repo_root);

    let output = command.output().ok()?;
    if !output.status.success() {
        return None;
    }

    Some(String::from_utf8(output.stdout).ok()?.trim().to_owned())
}

fn git_head_revision(repo_root: &Path) -> Option<String> {
    let git_dir = locate_git_dir(repo_root)?;
    let head = fs::read_to_string(git_dir.join("HEAD")).ok()?;
    let head = head.trim();
    let full_hash = if let Some(reference) = head.strip_prefix("ref: ") {
        resolve_git_reference(&git_dir, reference.trim())?
    } else {
        head.to_owned()
    };
    Some(shorten_hash(&full_hash).to_owned())
}

fn resolve_git_reference(git_dir: &Path, reference: &str) -> Option<String> {
    let ref_path = git_dir.join(reference);
    if let Ok(contents) = fs::read_to_string(&ref_path) {
        let hash = contents.trim();
        if !hash.is_empty() {
            return Some(hash.to_owned());
        }
    }

    let packed_refs = fs::read_to_string(git_dir.join("packed-refs")).ok()?;
    for line in packed_refs.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') || line.starts_with('^') {
            continue;
        }
        let (hash, packed_reference) = line.split_once(' ')?;
        if packed_reference == reference {
            return Some(hash.to_owned());
        }
    }

    None
}

fn shorten_hash(hash: &str) -> &str {
    let end = hash.len().min(8);
    &hash[..end]
}

fn compile_windows_resources() -> Result<(), String> {
    use image::{
        ColorType, ImageEncoder, codecs::ico::IcoEncoder, imageops::FilterType,
        io::Reader as ImageReader,
    };
    use std::{fs::File, io::Cursor, path::PathBuf};

    configure_windows_resource_tool_env();

    let out_dir = std::env::var("OUT_DIR")
        .map(PathBuf::from)
        .map_err(|error| format!("OUT_DIR is not set: {error}"))?;
    let icon_path = out_dir.join("vertex.ico");
    let decoded = ImageReader::new(Cursor::new(include_bytes!("../../Vertex.webp")))
        .with_guessed_format()
        .map_err(|error| format!("failed to detect vertex icon format: {error}"))?
        .decode()
        .map_err(|error| format!("failed to decode vertex icon source image: {error}"))?;
    let resized = decoded.resize(256, 256, FilterType::Lanczos3).to_rgba8();
    let mut icon_file = File::create(&icon_path)
        .map_err(|error| format!("failed to create generated .ico icon: {error}"))?;
    IcoEncoder::new(&mut icon_file)
        .write_image(
            resized.as_raw(),
            resized.width(),
            resized.height(),
            ColorType::Rgba8,
        )
        .map_err(|error| format!("failed to write generated .ico icon: {error}"))?;

    let mut resource = winresource::WindowsResource::new();
    resource.set_icon(icon_path.to_string_lossy().as_ref());
    resource
        .compile()
        .map_err(|error| format!("failed to compile Windows resources: {error}"))?;
    Ok(())
}

fn configure_windows_resource_tool_env() {
    if env::var_os("CROSS_COMPILE").is_some() || env::var_os("HOST") == env::var_os("TARGET") {
        return;
    }

    if env::var("TARGET").as_deref() == Ok("aarch64-pc-windows-msvc") {
        // winresource only uses this for GNU resource-tool defaults, but setting
        // it avoids a spurious warning before the MSVC llvm-rc path is selected.
        unsafe {
            env::set_var("CROSS_COMPILE", "llvm-");
        }
    }
}
