use super::*;

/// Mutable borrows of every `Config` field that is bound to a settings-UI control.
///
/// `Config::settings_bindings_mut` is the single exhaustive destructure of `Config`: adding a
/// field to `Config` fails to compile there until the field is either exposed through this view
/// or explicitly ignored with `_`. The `for_each_*_mut` visitors then only pick from this view.
